@unittest.skipUnless(os.getenv('AGRIRoute_POSTGRES_TESTS') == '1', 'Enable AGRIRoute_POSTGRES_TESTS=1 for isolated PostgreSQL concurrency tests')
class PostgresConcurrencyTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.schema='agriroute_phase9_test_'+uuid.uuid4().hex
        quote=engine.dialect.identifier_preparer.quote
        cls.quoted_schema=quote(cls.schema)
        # LIKE preserves production checks/indexes/types. Each ID gets its own
        # identity sequence so production sequences are never advanced.
        with engine.begin() as connection:
            connection.exec_driver_sql(f'CREATE SCHEMA {cls.quoted_schema}')
            for table in Base.metadata.sorted_tables:
                name=quote(table.name)
                connection.exec_driver_sql(f'CREATE TABLE {cls.quoted_schema}.{name} (LIKE public.{name} INCLUDING ALL)')
                connection.exec_driver_sql(f'ALTER TABLE {cls.quoted_schema}.{name} ALTER COLUMN id DROP DEFAULT')
                connection.exec_driver_sql(f'ALTER TABLE {cls.quoted_schema}.{name} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY')
        cls.test_engine=engine.execution_options(schema_translate_map={None:cls.schema})

    @classmethod
    def tearDownClass(cls):
        # The target is solely our freshly generated, exact test schema.
        assert cls.schema.startswith('agriroute_phase9_test_') and len(cls.schema)==54
        with engine.begin() as connection:
            connection.exec_driver_sql(f'DROP SCHEMA {cls.quoted_schema} CASCADE')

    def setUp(self):
        self.previous=dict(app.dependency_overrides)
        def isolated_db():
            with Session(self.test_engine) as db:
                try:
                    yield db
                except Exception:
                    db.rollback()
                    raise
        app.dependency_overrides[get_db]=isolated_db
        app.dependency_overrides[get_identity_db]=isolated_db
        app.dependency_overrides[get_current_user]=business_admin
        with Session(self.test_engine) as db:
            farmer=User(name='Isolated Farmer',email=uuid.uuid4().hex+'@test.example',role='FARMER')
            db.add(farmer)
            db.flush()
            batch=ProduceBatch(batch_code='TEST-'+uuid.uuid4().hex,farmer_id=farmer.id,crop_name='Tomato',initial_quantity_kg=Decimal('150'),expected_price_per_kg=Decimal('25'),harvest_date=date(2026,10,6),quality_grade='A',risk_level='CRITICAL')
            db.add(batch)
            db.commit()
            self.batch_id=batch.id

    def tearDown(self):
        app.dependency_overrides.clear()
        app.dependency_overrides.update(self.previous)

    def test_concurrent_requests_create_one_active_case(self):
        with Session(self.test_engine) as db:
            batch=db.get(ProduceBatch,self.batch_id)
            before=(batch.sold_quantity_kg,batch.remaining_quantity_kg,batch.rerouted_quantity_kg,batch.status)
            transaction_count=db.scalar(select(func.count()).select_from(Transaction))
        barrier=Barrier(4)
        def request_case():
            with TestClient(app) as client:
                barrier.wait(timeout=20)
                response=client.post(f'/produce/{self.batch_id}/rerouting')
                return response.status_code,response.json()
        with ThreadPoolExecutor(max_workers=4) as workers:
            results=list(workers.map(lambda _:request_case(),range(4)))
        self.assertTrue(all(status==200 for status,_ in results),results)
        self.assertEqual(len({body['id'] for _,body in results}),1)
        with Session(self.test_engine) as db:
            self.assertEqual(db.scalar(select(func.count()).select_from(RoutingCase).where(RoutingCase.produce_batch_id==self.batch_id)),1)
            batch=db.get(ProduceBatch,self.batch_id)
            self.assertEqual((batch.sold_quantity_kg,batch.remaining_quantity_kg,batch.rerouted_quantity_kg,batch.status),before)
            self.assertEqual(db.scalar(select(func.count()).select_from(Transaction)),transaction_count)


@unittest.skipUnless(os.getenv('AGRIRoute_LIVE_VERIFY') == '1', 'Enable AGRIRoute_LIVE_VERIFY=1 for read-only live batch 1 verification')
class LiveBatchVerificationTests(unittest.TestCase):
    def test_live_low_risk_batch_rejected_without_changes(self):
        self.assertFalse(app.dependency_overrides)
        app.dependency_overrides[get_current_user]=business_admin
        self.addCleanup(app.dependency_overrides.clear)
        with TestClient(app) as client:
            before=client.get('/produce/1').json()
            transactions=client.get('/transactions').json()
            cases=client.get('/routing-cases').json()
            readiness=client.get('/produce/1/routing-readiness').json()
            self.assertEqual(before['remaining_quantity_kg'],'150.000')
            self.assertEqual(before['risk_level'],'LOW')
            self.assertEqual(readiness['failed_matching_attempts'],1)
            self.assertFalse(readiness['rerouting_candidate'])
            response=client.post('/produce/1/rerouting')
            self.assertEqual(response.status_code,409,response.text)
            self.assertEqual(client.get('/produce/1').json(),before)
            self.assertEqual(client.get('/transactions').json(),transactions)
            self.assertEqual(client.get('/routing-cases').json(),cases)
            self.assertEqual(client.get('/produce/1/routing-readiness').json(),readiness)
